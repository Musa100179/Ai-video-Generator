# --- FUNCTION TO GENERATE IMAGE FROM TEXT (FREE - NO API KEY) ---
def generate_image(prompt):
    try:
        # Using Pollinations free AI image generator
        safe_prompt = requests.utils.quote(f"{prompt}, {video_style}, cinematic, 4k")
        url = f"https://image.pollinations.ai/prompt/{safe_prompt}"
        response = requests.get(url, timeout=30)
        img = Image.open(BytesIO(response.content))
        return img
    except:
        # Fallback blank image
        return Image.new('RGB', (1280, 720), color=(20,20,20))

# --- FUNCTION TO GENERATE VOICE ---
def generate_voice(text, character, temp_dir):
    # Assign unique voice settings per character
    slow = False
    if "Villain" in character or "Old Man" in character or "Narrator" in character:
        slow = True

    # Clean text - remove "Ali:" part
    clean_text = re.sub(r"^\w+:\s*", "", text)

    tts = gTTS(text=clean_text, lang=voice_lang, slow=slow)
    path = os.path.join(temp_dir, f"{abs(hash(text))}.mp3")
    tts.save(path)
    return path, clean_text

